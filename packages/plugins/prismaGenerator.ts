import { DatabaseIR, Field, Relation } from "@repo/types";

const toPascal = (value: string): string => value.charAt(0).toUpperCase() + value.slice(1);
const toCamel = (value: string): string => value.charAt(0).toLowerCase() + value.slice(1);

const mapFieldTypeToPrisma = (type: string, fieldName: string, modelName: string): string => {
  switch (type) {
    case "string": return "String";
    case "number": return "Int";
    case "boolean": return "Boolean";
    case "datetime": return "DateTime";
    case "json": return "Json";
    case "enum":
      throw new Error(
        `Generation Failed: Enum types are not currently supported by the database generator (Field '${fieldName}' on '${modelName}'). Documented requirement: Remove or map enum fields manually.`,
      );
    default:
      throw new Error(
        `Generation Failed: Unknown or unsupported field type '${type}' (Field '${fieldName}' on '${modelName}').`,
      );
  }
};

/**
 * Generate a Prisma schema from the canonical compiled DatabaseIR.
 * Relationship metadata is scoped to CompiledModel.relations. The semantic
 * analyzer indexes each non-self relationship on both participating models,
 * so relations are deduplicated before Prisma fields are emitted.
 */
export const generatePrismaSchema = (database: DatabaseIR): string => {
  let schema = `// This file is auto-generated by Backend OS
generator client {
  provider = "prisma-client-js"
}

datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}

`;

  const relationLines = new Map<string, string[]>();
  const modelFieldNames = new Map<string, Set<string>>();
  const modelNames = new Set<string>();

  // PHASE 0: Validate primary keys, model names, and declared field names.
  for (const model of database.models) {
    const prismaModelName = toPascal(model.tableName);
    const normalizedModelName = prismaModelName.toLowerCase();

    if (modelNames.has(normalizedModelName)) {
      throw new Error(
        `Generation Failed: Model name collision detected for '${prismaModelName}'. Models must have uniquely resolvable names.`,
      );
    }
    modelNames.add(normalizedModelName);

    const primaryKeyField = model.fields.find((field) => field.name === model.primaryKey);
    if (!primaryKeyField) {
      throw new Error(
        `Generation Failed: Primary key '${model.primaryKey}' declared on model '${model.tableName}' does not exist in its fields.`,
      );
    }

    if (primaryKeyField.type !== "string" && primaryKeyField.type !== "number") {
      throw new Error(
        `Generation Failed: Primary key '${primaryKeyField.name}' on '${model.tableName}' must be string or number. Found '${primaryKeyField.type}'.`,
      );
    }

    // Keep every declared name in the collision tracker, including relation
    // placeholder fields that are intentionally not emitted as scalar fields.
    modelFieldNames.set(
      model.tableName.toLowerCase(),
      new Set(model.fields.map((field) => field.name)),
    );
  }

  // PHASE 1: Collect model-scoped relations and deduplicate symmetric indexes.
  // The type is deliberately not part of the key so conflicting types for the
  // same endpoints are detected rather than being treated as separate edges.
  const uniqueRelations = new Map<string, Relation>();

  for (const model of database.models) {
    for (const relation of model.relations) {
      const relationId = JSON.stringify([
        relation.source.toLowerCase(),
        relation.sourceField,
        relation.target.toLowerCase(),
        relation.targetField,
      ]);
      const existing = uniqueRelations.get(relationId);

      if (existing && existing.type !== relation.type) {
        throw new Error(
          `Generation Failed: Conflicting relation types for identical endpoints between '${relation.source}' and '${relation.target}'.`,
        );
      }

      if (!existing) uniqueRelations.set(relationId, relation);
    }
  }

  const sortedRelations = [...uniqueRelations.values()].sort((left, right) =>
    left.source.toLowerCase().localeCompare(right.source.toLowerCase()) ||
    left.sourceField.localeCompare(right.sourceField) ||
    left.target.toLowerCase().localeCompare(right.target.toLowerCase()) ||
    left.targetField.localeCompare(right.targetField) ||
    left.type.localeCompare(right.type),
  );

  for (const relation of sortedRelations) {
    if (relation.type !== "one-to-many") {
      throw new Error(
        `Generation Failed: Unsupported relation type '${relation.type}'. Only 'one-to-many' is fully supported.`,
      );
    }

    const sourceModel = database.models.find(
      (model) => model.tableName.toLowerCase() === relation.source.toLowerCase(),
    );
    const targetModel = database.models.find(
      (model) => model.tableName.toLowerCase() === relation.target.toLowerCase(),
    );

    if (!sourceModel) {
      throw new Error(`Generation Failed: Relation source model '${relation.source}' not found.`);
    }
    if (!targetModel) {
      throw new Error(`Generation Failed: Relation target model '${relation.target}' not found.`);
    }

    if (relation.sourceField !== sourceModel.primaryKey) {
      throw new Error(
        `Generation Failed: Relation from '${relation.source}' to '${relation.target}' must reference the source's primary key ('${sourceModel.primaryKey}'). Referencing '${relation.sourceField}' is unsupported.`,
      );
    }

    const sourcePrimaryKey = sourceModel.fields.find(
      (field) => field.name === sourceModel.primaryKey,
    );
    // The primary-key pass above guarantees this field exists.
    if (!sourcePrimaryKey) {
      throw new Error(
        `Generation Failed: Primary key '${sourceModel.primaryKey}' declared on model '${sourceModel.tableName}' does not exist in its fields.`,
      );
    }

    const targetForeignKey = targetModel.fields.find(
      (field) => field.name === relation.targetField,
    );
    if (!targetForeignKey) {
      throw new Error(
        `Generation Failed: Target foreign key field '${relation.targetField}' is missing from model '${relation.target}'. Explicitly declare this field to establish relation requiredness.`,
      );
    }

    if (targetForeignKey.type !== sourcePrimaryKey.type) {
      throw new Error(
        `Generation Failed: Foreign key '${relation.targetField}' type (${targetForeignKey.type}) does not match referenced primary key '${relation.sourceField}' type (${sourcePrimaryKey.type}).`,
      );
    }

    const sourceFieldNames = modelFieldNames.get(sourceModel.tableName.toLowerCase());
    const targetFieldNames = modelFieldNames.get(targetModel.tableName.toLowerCase());
    if (!sourceFieldNames || !targetFieldNames) {
      throw new Error("Generation Failed: Internal field collision tracking could not find a relation model.");
    }

    const sourceRelationField = `${toCamel(relation.target)}List`;
    if (sourceFieldNames.has(sourceRelationField)) {
      throw new Error(
        `Generation Failed: Relation field collision. Model '${sourceModel.tableName}' already contains field '${sourceRelationField}'.`,
      );
    }
    sourceFieldNames.add(sourceRelationField);

    const targetRelationField = `${toCamel(relation.source)}Ref`;
    if (targetFieldNames.has(targetRelationField)) {
      throw new Error(
        `Generation Failed: Relation field collision. Model '${targetModel.tableName}' already contains field '${targetRelationField}'.`,
      );
    }
    targetFieldNames.add(targetRelationField);

    const relationOptionality = targetForeignKey.required ? "" : "?";
    const prismaRelationName = `Rel_${toPascal(relation.source)}_${toPascal(relation.target)}_${relation.targetField}`;

    const sourceLines = relationLines.get(sourceModel.tableName) ?? [];
    sourceLines.push(
      `  ${sourceRelationField} ${toPascal(relation.target)}[] @relation("${prismaRelationName}")`,
    );
    relationLines.set(sourceModel.tableName, sourceLines);

    const targetLines = relationLines.get(targetModel.tableName) ?? [];
    targetLines.push(
      `  ${targetRelationField} ${toPascal(relation.source)}${relationOptionality} @relation("${prismaRelationName}", fields: [${relation.targetField}], references: [${relation.sourceField}])`,
    );
    relationLines.set(targetModel.tableName, targetLines);
  }

  // PHASE 2: Emit scalar fields and the validated relation fields.
  for (const model of database.models) {
    schema += `model ${toPascal(model.tableName)} {\n`;

    for (const field of model.fields) {
      if (field.type === "relation") continue;

      const prismaType = mapFieldTypeToPrisma(field.type, field.name, model.tableName);
      const isPrimaryKey = field.name === model.primaryKey;
      const idAttributes = isPrimaryKey
        ? prismaType === "Int"
          ? " @id @default(autoincrement())"
          : " @id @default(uuid())"
        : "";
      const optionality = !field.required && !isPrimaryKey ? "?" : "";

      schema += `  ${field.name} ${prismaType}${optionality}${idAttributes}\n`;
    }

    const modelRelations = relationLines.get(model.tableName) ?? [];
    for (const relationLine of modelRelations) schema += `${relationLine}\n`;
    schema += `}\n\n`;
  }

  return schema.trim() + "\n";
};
