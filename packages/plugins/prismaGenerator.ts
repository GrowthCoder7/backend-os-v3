import { DatabaseIR, Field, Relation } from "@repo/types";

const compareText = (left: string, right: string): number => (left < right ? -1 : left > right ? 1 : 0);
const toPascal = (value: string): string => value.length === 0 ? value : value.charAt(0).toUpperCase() + value.slice(1);
const toCamel = (value: string): string => value.length === 0 ? value : value.charAt(0).toLowerCase() + value.slice(1);

const mapFieldTypeToPrisma = (type: string, fieldName: string, modelName: string): string => {
  switch (type) {
    case "string": return "String";
    case "number": return "Int";
    case "boolean": return "Boolean";
    case "datetime": return "DateTime";
    case "json": return "Json";
    case "enum":
      throw new Error(`Generation Failed: Enum types are not currently supported (field '${fieldName}' on '${modelName}').`);
    default:
      throw new Error(`Generation Failed: Unknown or unsupported field type '${type}' (field '${fieldName}' on '${modelName}').`);
  }
};

const relationIdentity = (relation: Relation): string =>
  `${relation.source.toLowerCase()}.${relation.sourceField}->${relation.target.toLowerCase()}.${relation.targetField}`;

const canonicalRelationSortKey = (relation: Relation): string =>
  `${relation.source.toLowerCase()}\u0000${relation.sourceField}\u0000${relation.target.toLowerCase()}\u0000${relation.targetField}\u0000${relation.type}`;

export const generatePrismaSchema = (database: DatabaseIR): string => {
  const models = [...database.models].sort((left, right) => compareText(left.tableName, right.tableName));
  const schemaParts: string[] = [
    "// This file is auto-generated by Backend OS",
    "generator client {\n  provider = \"prisma-client-js\"\n}",
    "datasource db {\n  provider = \"postgresql\"\n  url      = env(\"DATABASE_URL\")\n}",
  ];

  const modelByLowerName = new Map<string, (typeof models)[number]>();
  const modelFieldNames = new Map<string, Set<string>>();
  const renderedModelNames = new Set<string>();

  for (const model of models) {
    const prismaModelName = toPascal(model.tableName);
    const renderedModelKey = prismaModelName.toLowerCase();
    if (renderedModelNames.has(renderedModelKey)) {
      throw new Error(`Generation Failed: Model name collision detected for '${prismaModelName}'. Models must have uniquely resolvable names.`);
    }
    renderedModelNames.add(renderedModelKey);

    const lookupKey = model.tableName.toLowerCase();
    if (modelByLowerName.has(lookupKey)) {
      throw new Error(`Generation Failed: Duplicate model name '${model.tableName}' ignoring case.`);
    }
    modelByLowerName.set(lookupKey, model);

    const primaryKeyField = model.fields.find((field) => field.name === model.primaryKey);
    if (!primaryKeyField) {
      throw new Error(`Generation Failed: Primary key '${model.primaryKey}' declared on model '${model.tableName}' does not exist in its fields.`);
    }
    if (primaryKeyField.type !== "string" && primaryKeyField.type !== "number") {
      throw new Error(`Generation Failed: Primary key '${primaryKeyField.name}' on '${model.tableName}' must be string or number. Found '${primaryKeyField.type}'.`);
    }

    const fieldNames = new Set<string>();
    for (const field of model.fields) {
      if (fieldNames.has(field.name)) {
        throw new Error(`Generation Failed: Duplicate field '${field.name}' on model '${model.tableName}'.`);
      }
      fieldNames.add(field.name);
    }
    modelFieldNames.set(lookupKey, new Set(model.fields.filter((field) => field.type !== "relation").map((field) => field.name)));
  }

  // Normalize relation endpoint names to the canonical table casing before deduplication.
  // Identical logical relations emitted by more than one model are rendered exactly once.
  const uniqueRelations = new Map<string, Relation>();
  for (const model of models) {
    const relations = Array.isArray(model.relations) ? model.relations : [];
    for (const relation of relations) {
      const sourceModel = modelByLowerName.get(relation.source.toLowerCase());
      const targetModel = modelByLowerName.get(relation.target.toLowerCase());
      if (!sourceModel) throw new Error(`Generation Failed: Relation source model '${relation.source}' not found.`);
      if (!targetModel) throw new Error(`Generation Failed: Relation target model '${relation.target}' not found.`);

      const canonicalRelation: Relation = {
        ...relation,
        source: sourceModel.tableName,
        target: targetModel.tableName,
      };
      const identity = relationIdentity(canonicalRelation);
      const existing = uniqueRelations.get(identity);
      if (existing && existing.type !== canonicalRelation.type) {
        throw new Error(`Generation Failed: Conflicting relation types for identical endpoints between '${canonicalRelation.source}' and '${canonicalRelation.target}'.`);
      }

      if (!existing || compareText(canonicalRelationSortKey(canonicalRelation), canonicalRelationSortKey(existing)) < 0) {
        uniqueRelations.set(identity, canonicalRelation);
      }
    }
  }

  const relationLines = new Map<string, string[]>();
  const sortedRelations = [...uniqueRelations.values()].sort((left, right) =>
    compareText(canonicalRelationSortKey(left), canonicalRelationSortKey(right)),
  );

  for (const relation of sortedRelations) {
    if (relation.type !== "one-to-many") {
      throw new Error(`Generation Failed: Unsupported relation type '${relation.type}'. Only 'one-to-many' is fully supported.`);
    }

    const sourceModel = modelByLowerName.get(relation.source.toLowerCase());
    const targetModel = modelByLowerName.get(relation.target.toLowerCase());
    if (!sourceModel || !targetModel) {
      throw new Error(`Generation Failed: Relation source or target model was not found.`);
    }
    if (relation.sourceField !== sourceModel.primaryKey) {
      throw new Error(`Generation Failed: Relation from '${relation.source}' to '${relation.target}' must reference source primary key '${sourceModel.primaryKey}'.`);
    }

    const sourcePrimaryKey = sourceModel.fields.find((field) => field.name === sourceModel.primaryKey);
    const targetForeignKey = targetModel.fields.find((field) => field.name === relation.targetField);
    if (!sourcePrimaryKey) {
      throw new Error(`Generation Failed: Source primary-key field '${sourceModel.primaryKey}' is missing from '${sourceModel.tableName}'.`);
    }
    if (!targetForeignKey) {
      throw new Error(`Generation Failed: Target foreign-key field '${relation.targetField}' is missing from model '${targetModel.tableName}'. Explicitly declare this field.`);
    }
    if (targetForeignKey.type !== sourcePrimaryKey.type) {
      throw new Error(`Generation Failed: Foreign key '${relation.targetField}' type (${targetForeignKey.type}) does not match referenced primary key '${relation.sourceField}' type (${sourcePrimaryKey.type}).`);
    }

    const sourceFields = modelFieldNames.get(sourceModel.tableName.toLowerCase());
    const targetFields = modelFieldNames.get(targetModel.tableName.toLowerCase());
    if (!sourceFields || !targetFields) throw new Error("Generation Failed: Model field index is inconsistent.");

    const targetCollectionName = `${toCamel(targetModel.tableName)}List`;
    if (sourceFields.has(targetCollectionName)) {
      throw new Error(`Generation Failed: Relation field collision. Model '${sourceModel.tableName}' already contains field '${targetCollectionName}'.`);
    }
    sourceFields.add(targetCollectionName);

    const sourceReferenceName = `${toCamel(sourceModel.tableName)}Ref`;
    if (targetFields.has(sourceReferenceName)) {
      throw new Error(`Generation Failed: Relation field collision. Model '${targetModel.tableName}' already contains field '${sourceReferenceName}'.`);
    }
    targetFields.add(sourceReferenceName);

    const optionalMarker = targetForeignKey.required ? "" : "?";
    const relationName = `Rel_${toPascal(sourceModel.tableName)}_${toPascal(targetModel.tableName)}_${relation.targetField}`;
    const sourceLines = relationLines.get(sourceModel.tableName.toLowerCase()) ?? [];
    sourceLines.push(`  ${targetCollectionName} ${toPascal(targetModel.tableName)}[] @relation("${relationName}")`);
    relationLines.set(sourceModel.tableName.toLowerCase(), sourceLines);

    const targetLines = relationLines.get(targetModel.tableName.toLowerCase()) ?? [];
    targetLines.push(`  ${sourceReferenceName} ${toPascal(sourceModel.tableName)}${optionalMarker} @relation("${relationName}", fields: [${relation.targetField}], references: [${relation.sourceField}])`);
    relationLines.set(targetModel.tableName.toLowerCase(), targetLines);
  }

  for (const lines of relationLines.values()) lines.sort(compareText);

  for (const model of models) {
    const modelName = toPascal(model.tableName);
    const fieldLines = [...model.fields]
      .filter((field) => field.type !== "relation")
      .sort((left, right) => compareText(left.name, right.name))
      .map((field: Field) => {
        const prismaType = mapFieldTypeToPrisma(field.type, field.name, model.tableName);
        const isPrimaryKey = field.name === model.primaryKey;
        const idAnnotation = isPrimaryKey
          ? prismaType === "Int" ? " @id @default(autoincrement())" : " @id @default(uuid())"
          : "";
        const optionalMarker = !field.required && !isPrimaryKey ? "?" : "";
        return `  ${field.name} ${prismaType}${optionalMarker}${idAnnotation}`;
      });
    const modelRelations = relationLines.get(model.tableName.toLowerCase()) ?? [];
    schemaParts.push(`model ${modelName} {\n${[...fieldLines, ...modelRelations].join("\n")}\n}`);
  }

  return `${schemaParts.join("\n\n").trim()}\n`;
};
